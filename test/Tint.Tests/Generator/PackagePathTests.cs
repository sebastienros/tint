using Microsoft.CodeAnalysis;
using Xunit;

namespace Tint.Tests.Generator;

// Items included from a package folder (Tint.Grammars.Sources, Tint.Themes.Sources): absolute paths outside the project
// directory, with the platform's separators.
public sealed class PackagePathTests
{
    private const string Grammar = """{ "scopeName": "source.pkg", "patterns": [ { "match": "x", "name": "keyword.x" } ] }""";

    private static string GrammarsFolder { get; } = Path.Combine(Path.GetTempPath(), "tint-generator-tests", "packages", "tint.grammars.sources", "1.0.0", "content", "grammars");

    private static string GrammarPath { get; } = Path.Combine(GrammarsFolder, "pkg", "syntaxes", "pkg.tmLanguage.json");

    [Fact]
    public void AnItemFromAPackageFolderGeneratesItsClass()
    {
        var run = GeneratorHarness.Run([TestFile.Grammar(GrammarPath, Grammar)]);

        Assert.Empty(run.GeneratorDiagnostics);
        Assert.Contains("Test.Root.PkgGrammar.g.cs", run.Sources.Keys);
        Assert.Contains("// Generated by Tint.Generator from pkg.tmLanguage.json.", run.Source("Test.Root.PkgGrammar"));
    }

    [Fact]
    public void AnAbsoluteAttributePathBindsTheItemWithEitherSeparator()
    {
        foreach (var path in new[] { GrammarPath, GrammarPath.Replace('\\', '/') })
        {
            var run = GeneratorHarness.Run([TestFile.Grammar(GrammarPath, Grammar)], $$"""
                [Tint.TextMateGrammar(@"{{path}}")]
                public partial class Bound;
                """);

            Assert.Empty(run.Tint("TINT001"));
            Assert.Contains("Bound.g.cs", run.Sources.Keys);
            Assert.DoesNotContain("Test.Root.PkgGrammar.g.cs", run.Sources.Keys);
        }
    }

    [Fact]
    public void AnAttributePathCanStartWithTheSourcesPathProperty()
    {
        var run = GeneratorHarness.Run(
            [TestFile.Grammar(GrammarPath, Grammar)],
            """
            [Tint.TextMateGrammar("$(TintGrammarsSourcesPath)pkg/syntaxes/pkg.tmLanguage.json")]
            public partial class Bound;
            """,
            properties: new Dictionary<string, string> { ["TintGrammarsSourcesPath"] = GrammarsFolder + Path.DirectorySeparatorChar });

        Assert.Empty(run.Tint("TINT001"));
        Assert.Contains("Bound.g.cs", run.Sources.Keys);
    }

    [Fact]
    public void ARelativeAttributePathBindsTheOneItemItEndsWith()
    {
        var source = """
            [Tint.TextMateGrammar("pkg/syntaxes/pkg.tmLanguage.json")]
            public partial class Bound;
            """;

        var run = GeneratorHarness.Run([TestFile.Grammar(GrammarPath, Grammar)], source);
        Assert.Empty(run.Tint("TINT001"));
        Assert.Contains("Bound.g.cs", run.Sources.Keys);

        // Two items end with the path: ambiguous, so nothing binds.
        var other = Path.Combine(Path.GetTempPath(), "tint-generator-tests", "other", "pkg", "syntaxes", "pkg.tmLanguage.json");
        var ambiguous = GeneratorHarness.Run([TestFile.Grammar(GrammarPath, Grammar), TestFile.Grammar(other, Grammar, ("Name", "Other"))], source);
        Assert.Single(ambiguous.Tint("TINT001"));
    }

    [Fact]
    public void DiagnosticsNameAFileOutsideTheProjectByItsFullPath()
    {
        var run = GeneratorHarness.Run([TestFile.Grammar(GrammarPath, null)]);

        var diagnostic = Assert.Single(run.Tint("TINT003"));
        Assert.Equal($"'{Path.GetFullPath(GrammarPath).Replace('\\', '/')}' cannot be read as a grammar: the file cannot be read", diagnostic.GetMessage());
    }

    [Fact]
    public void Tint005NamesTheSourcesPackagePathOfVSCodeScopes()
    {
        var run = GeneratorHarness.Run([TestFile.Grammar("html.json", """
            { "scopeName": "text.html.x", "patterns": [ { "include": "source.css" }, { "include": "source.unknown" } ] }
            """)]);

        var diagnostic = Assert.Single(run.Tint("TINT005"));
        Assert.Equal(DiagnosticSeverity.Info, diagnostic.Severity);
        Assert.Contains("source.css ($(TintGrammarsSourcesPath)css/syntaxes/css.tmLanguage.json), source.unknown", diagnostic.GetMessage());
    }
}
