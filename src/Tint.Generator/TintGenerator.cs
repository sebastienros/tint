using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;
using Tint.Loading;

namespace Tint.Generator;

/// <summary>
/// Compiles <c>TintGrammar</c> and <c>TintTheme</c> items into <c>IGrammarSource</c> and <c>IThemeSource</c> classes,
/// bound either by <c>[TextMateGrammar]</c> / <c>[TextMateTheme]</c> on a partial class or by the item alone.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class TintGenerator : IIncrementalGenerator
{
    internal const string GrammarAttribute = "Tint.TextMateGrammarAttribute";
    internal const string ThemeAttribute = "Tint.TextMateThemeAttribute";

    private const string AttributesSource = """
        // <auto-generated/>
        #nullable enable

        namespace Tint
        {
            /// <summary>
            /// Generates an <c>IGrammarSource</c> implementation on this partial class from a <c>TintGrammar</c> (or
            /// <c>AdditionalFiles</c>) item whose path, relative to the project directory, is the constructor argument.
            /// </summary>
            [global::Microsoft.CodeAnalysis.EmbeddedAttribute]
            [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
            [global::System.Diagnostics.Conditional("TINT_KEEP_ATTRIBUTES")]
            internal sealed class TextMateGrammarAttribute : global::System.Attribute
            {
                /// <summary>Binds the class to a grammar file.</summary>
                /// <param name="path">The grammar file, relative to the project directory.</param>
                public TextMateGrammarAttribute(string path)
                {
                    Path = path;
                }

                /// <summary>The grammar file, relative to the project directory.</summary>
                public string Path { get; }

                /// <summary>Compile the grammar's patterns ahead of time with GregsEx kernels (.NET 8 or later).</summary>
                public bool Kernels { get; set; }

                /// <summary>The language identifier, for example <c>csharp</c>.</summary>
                public string? LanguageId { get; set; }

                /// <summary>Display names of the language.</summary>
                public string[]? Aliases { get; set; }

                /// <summary>File extensions, with the leading dot.</summary>
                public string[]? FileExtensions { get; set; }

                /// <summary>Embedded languages as <c>scope=languageId</c> pairs.</summary>
                public string[]? EmbeddedLanguages { get; set; }

                /// <summary>Scope names of the grammars this grammar injects into.</summary>
                public string[]? InjectTo { get; set; }

                /// <summary>The injection selector, when it is not in the grammar file.</summary>
                public string? InjectionSelector { get; set; }

                /// <summary>Token type overrides as <c>selector=comment|string|regex|other</c> pairs.</summary>
                public string[]? TokenTypes { get; set; }

                /// <summary>Scope selectors of tokens whose brackets are balanced (default: every scope).</summary>
                public string[]? BalancedBracketScopes { get; set; }

                /// <summary>Scope selectors of tokens whose brackets are not balanced.</summary>
                public string[]? UnbalancedBracketScopes { get; set; }
            }

            /// <summary>
            /// Generates an <c>IThemeSource</c> implementation on this partial class from a <c>TintTheme</c> (or
            /// <c>AdditionalFiles</c>) item whose path, relative to the project directory, is the constructor argument.
            /// </summary>
            [global::Microsoft.CodeAnalysis.EmbeddedAttribute]
            [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
            [global::System.Diagnostics.Conditional("TINT_KEEP_ATTRIBUTES")]
            internal sealed class TextMateThemeAttribute : global::System.Attribute
            {
                /// <summary>Binds the class to a theme file.</summary>
                /// <param name="path">The theme file, relative to the project directory.</param>
                public TextMateThemeAttribute(string path)
                {
                    Path = path;
                }

                /// <summary>The theme file, relative to the project directory.</summary>
                public string Path { get; }

                /// <summary>
                /// <c>VSCode</c> (default) applies VS Code's default rule and drops other scopeless rules; <c>Raw</c> keeps
                /// the rules as written.
                /// </summary>
                public string? ThemeMode { get; set; }
            }
        }
        """;

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static context =>
        {
            context.AddEmbeddedAttributeDefinition();
            context.AddSource("Tint.Attributes.g.cs", SourceText.From(AttributesSource, Encoding.UTF8));
        });

        var globals = context.AnalyzerConfigOptionsProvider.Select(static (provider, _) => GlobalOptions.From(provider.GlobalOptions));
        var facts = context.CompilationProvider.Select(static (compilation, _) => ReadFacts(compilation));

        var files = context.AdditionalTextsProvider
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Combine(globals)
            .Select(static (input, cancellationToken) => ReadFile(input.Left.Left, input.Left.Right.GetOptions(input.Left.Left), input.Right, cancellationToken))
            .Where(static file => file is not null)
            .Select(static (file, _) => file!)
            .Collect()
            .Select(static (files, _) => files.ToEquatableArray());

        var grammarTargets = context.SyntaxProvider.ForAttributeWithMetadataName(
            GrammarAttribute,
            static (node, _) => node is ClassDeclarationSyntax,
            static (attributeContext, _) => ReadTarget(attributeContext, SourceKind.Grammar));
        var themeTargets = context.SyntaxProvider.ForAttributeWithMetadataName(
            ThemeAttribute,
            static (node, _) => node is ClassDeclarationSyntax,
            static (attributeContext, _) => ReadTarget(attributeContext, SourceKind.Theme));
        var targets = grammarTargets.Collect()
            .Combine(themeTargets.Collect())
            .Select(static (pair, _) => pair.Left.AddRange(pair.Right).ToEquatableArray());

        var plan = files.Combine(targets).Combine(globals)
            .Select(static (input, _) => Plan.Create(input.Left.Left, input.Left.Right, input.Right));

        context.RegisterSourceOutput(plan.Select(static (plan, _) => plan.Diagnostics), static (context, diagnostics) =>
        {
            foreach (var diagnostic in diagnostics)
            {
                context.ReportDiagnostic(diagnostic.ToDiagnostic());
            }
        });

        var gregsEx = facts.Combine(globals).Select(static (input, _) => new GregsExContext(
            GregsExShim.FindPackageRoot(input.Right.GregsExPackagePath, input.Left.GregsExReferencePath),
            input.Left.SupportsKernels));

        var grammars = plan.SelectMany(static (plan, _) => plan.Units.Where(u => u.Kind == SourceKind.Grammar))
            .Combine(gregsEx)
            .Select(static (input, cancellationToken) => GrammarEmitter.Generate(input.Left, input.Right, cancellationToken));
        context.RegisterSourceOutput(grammars, Emit);

        var themes = plan.SelectMany(static (plan, _) => plan.Units.Where(u => u.Kind == SourceKind.Theme))
            .Combine(files)
            .Select(static (input, cancellationToken) => ThemeEmitter.Generate(input.Left, input.Right, cancellationToken));
        context.RegisterSourceOutput(themes, Emit);

        // Opt-in aggregate classes (TintGrammarsClass, TintThemesClass) over every generated class of the compilation.
        RegisterAggregate(context, grammars, globals.Select(static (g, _) => AggregateTarget.From(g.GrammarsClass, g.RootNamespace)), SourceKind.Grammar);
        RegisterAggregate(context, themes, globals.Select(static (g, _) => AggregateTarget.From(g.ThemesClass, g.RootNamespace)), SourceKind.Theme);
    }

    private static void RegisterAggregate(
        IncrementalGeneratorInitializationContext context,
        IncrementalValuesProvider<GenerationResult> results,
        IncrementalValueProvider<AggregateTarget?> target,
        SourceKind kind)
    {
        var entries = results
            .Select(static (result, _) => result.Entry)
            .Where(static entry => entry is not null)
            .Select(static (entry, _) => entry!)
            .Collect()
            .Select(static (entries, _) => entries.ToEquatableArray());
        context.RegisterSourceOutput(entries.Combine(target), (context, input) =>
        {
            if (input.Right is { } aggregate)
            {
                var result = AggregateEmitter.Generate(aggregate, kind, input.Left);
                context.AddSource(result.HintName + ".g.cs", SourceText.From(result.Source!, Encoding.UTF8));
            }
        });
    }

    private static void Emit(SourceProductionContext context, GenerationResult result)
    {
        foreach (var diagnostic in result.Diagnostics)
        {
            context.ReportDiagnostic(diagnostic.ToDiagnostic());
        }

        if (result.Source is not null)
        {
            context.AddSource(result.HintName + ".g.cs", SourceText.From(result.Source, Encoding.UTF8));
        }

        if (result.KernelSource is not null)
        {
            context.AddSource(result.HintName + ".Kernels.g.cs", SourceText.From(result.KernelSource, Encoding.UTF8));
        }
    }

    private static CompilationFacts ReadFacts(Compilation compilation)
    {
        string? gregsEx = null;
        foreach (var reference in compilation.References)
        {
            if (reference is PortableExecutableReference { FilePath: { } path }
                && string.Equals(Path.GetFileName(path), "GregsEx.dll", StringComparison.OrdinalIgnoreCase))
            {
                gregsEx = path;
                break;
            }
        }

        // GregsEx kernels use .NET 8 APIs; PatternGenerator checks for this one.
        var supportsKernels = compilation.GetTypeByMetadataName("System.MemoryExtensions")?.GetMembers("IndexOfAnyInRange").Length > 0;
        return new CompilationFacts(gregsEx, supportsKernels);
    }

    // Plain AdditionalFiles a theme may include or an attribute may bind.
    private static readonly string[] s_textExtensions = [".json", ".tmLanguage", ".tmTheme", ".plist", ".xml"];

    private static ProjectFile? ReadFile(AdditionalText text, AnalyzerConfigOptions options, GlobalOptions globals, CancellationToken cancellationToken)
    {
        string? Get(string name) => options.TryGetValue("build_metadata.AdditionalFiles." + name, out var value) && !string.IsNullOrWhiteSpace(value) ? Unescape(value.Trim()) : null;

        SourceKind? kind = Get("TintKind") switch
        {
            "Grammar" => SourceKind.Grammar,
            "Theme" => SourceKind.Theme,
            _ => null,
        };

        // Files without a kind matter only as theme includes or as the target of an attribute.
        var fullPath = PathUtilities.Normalize(text.Path, globals.ProjectDirectory);
        if (kind is null && !s_textExtensions.Any(e => fullPath.EndsWith(e, StringComparison.OrdinalIgnoreCase)))
        {
            return null;
        }

        var content = text.GetText(cancellationToken)?.ToString();
        string? scopeName = null;
        if (content is not null && kind == SourceKind.Grammar && Get("Name") is null)
        {
            scopeName = ReadScopeName(fullPath, content);
        }

        var kernels = Get("Kernels");
        return new ProjectFile(
            fullPath,
            text.Path,
            kind,
            content,
            scopeName,
            Get("Name"),
            Get("Namespace"),
            Get("Accessibility"),
            kernels is null ? null : GlobalOptions.IsTrue(kernels),
            SourceSettings.FromMetadata(Get));
    }

    // Tint.props writes '#' and '%' as %23 and %25: the analyzer config file would cut a value at '#'.
    private static string Unescape(string value)
    {
        if (value.IndexOf('%') < 0)
        {
            return value;
        }

        var builder = new StringBuilder(value.Length);
        for (var i = 0; i < value.Length; i++)
        {
            if (value[i] == '%' && i + 2 < value.Length && value[i + 1] == '2' && value[i + 2] is '3' or '5')
            {
                builder.Append(value[i + 2] == '3' ? '#' : '%');
                i += 2;
            }
            else
            {
                builder.Append(value[i]);
            }
        }

        return builder.ToString();
    }

    // Naming an item-only grammar needs its scope name; a file that does not parse is reported when it is generated.
    private static string? ReadScopeName(string path, string content)
    {
        try
        {
            var utf8 = Encoding.UTF8.GetBytes(content);
            var tree = path.EndsWith(".json", StringComparison.OrdinalIgnoreCase) ? DocumentTree.ParseJson(utf8) : DocumentTree.ParsePlist(utf8);
            return (tree as TreeMap)?.Get("scopeName") as string;
        }
        catch (Exception e) when (e is FormatException or System.Xml.XmlException)
        {
            return null;
        }
    }

    private static AttributeTarget ReadTarget(GeneratorAttributeSyntaxContext context, SourceKind kind)
    {
        var symbol = (INamedTypeSymbol)context.TargetSymbol;
        var attribute = context.Attributes[0];
        var path = attribute.ConstructorArguments.Length > 0 ? attribute.ConstructorArguments[0].Value as string ?? string.Empty : string.Empty;
        bool? kernels = null;
        var named = new Dictionary<string, TypedConstant>(StringComparer.Ordinal);
        foreach (var argument in attribute.NamedArguments)
        {
            named[argument.Key] = argument.Value;
            if (argument.Key == "Kernels" && argument.Value.Value is bool value)
            {
                kernels = value;
            }
        }

        string? String(string name) => named.TryGetValue(name, out var value) ? SourceSettings.NullIfEmpty(value.Value as string) : null;
        EquatableArray<string> Array(string name) => named.TryGetValue(name, out var value) && value.Kind == TypedConstantKind.Array && !value.IsNull
            ? value.Values.Select(v => v.Value as string).Where(v => !string.IsNullOrWhiteSpace(v)).Select(v => v!.Trim()).ToEquatableArray()
            : default;

        var settings = new SourceSettings(
            String("LanguageId"),
            Array("Aliases"),
            Array("FileExtensions"),
            Array("EmbeddedLanguages"),
            Array("InjectTo"),
            String("InjectionSelector"),
            Array("TokenTypes"),
            named.ContainsKey("BalancedBracketScopes") ? Array("BalancedBracketScopes") : null,
            Array("UnbalancedBracketScopes"),
            String("ThemeMode"));

        var isPartial = context.TargetNode is ClassDeclarationSyntax declaration
            && declaration.Modifiers.Any(m => m.Text == "partial");
        var containingTypes = new List<string>();
        var valid = isPartial && !symbol.IsStatic && !symbol.IsGenericType;
        var isPublic = symbol.DeclaredAccessibility == Accessibility.Public;
        for (var containing = symbol.ContainingType; containing is not null; containing = containing.ContainingType)
        {
            valid &= !containing.IsGenericType && containing.DeclaringSyntaxReferences.Length > 0;
            isPublic &= containing.DeclaredAccessibility == Accessibility.Public;
            var keyword = containing.IsRecord
                ? (containing.TypeKind == TypeKind.Struct ? "record struct" : "record")
                : containing.TypeKind switch
                {
                    TypeKind.Struct => "struct",
                    TypeKind.Interface => "interface",
                    _ => "class",
                };
            containingTypes.Insert(0, "partial " + keyword + " " + containing.Name);
        }

        var ns = symbol.ContainingNamespace is { IsGlobalNamespace: false } containingNamespace ? containingNamespace.ToDisplayString() : null;
        return new AttributeTarget(
            kind,
            path,
            kernels,
            settings,
            symbol.Name,
            ns,
            containingTypes.ToEquatableArray(),
            symbol.ToDisplayString(),
            valid,
            isPublic,
            LocationInfo.From(attribute.ApplicationSyntaxReference?.GetSyntax().GetLocation() ?? symbol.Locations.FirstOrDefault()));
    }

    // Binds attributes and items to the classes to generate, and reports what cannot be bound.
    private sealed record Plan(EquatableArray<GenerationUnit> Units, EquatableArray<DiagnosticInfo> Diagnostics)
    {
        public static Plan Create(EquatableArray<ProjectFile> files, EquatableArray<AttributeTarget> targets, GlobalOptions globals)
        {
            var units = new List<GenerationUnit>();
            var diagnostics = new List<DiagnosticInfo>();
            var bound = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            foreach (var target in targets)
            {
                var attributeName = target.Kind == SourceKind.Grammar ? "TextMateGrammar" : "TextMateTheme";
                if (!target.IsValidTarget)
                {
                    diagnostics.Add(DiagnosticInfo.Create(TintDiagnostics.InvalidTarget, target.Location, target.TypeDisplay, attributeName));
                    continue;
                }

                var path = globals.ExpandSourcesPaths(target.Path);
                var full = PathUtilities.Normalize(path, globals.ProjectDirectory);
                var file = files.FirstOrDefault(f => f.Text is not null && PathUtilities.PathEquals(f.FullPath, full))
                    ?? UniqueSuffixMatch(files, path);
                if (file is null)
                {
                    diagnostics.Add(DiagnosticInfo.Create(
                        TintDiagnostics.UnmatchedPath, target.Location, attributeName, target.Path, target.TypeDisplay, target.Kind == SourceKind.Grammar ? "TintGrammar" : "TintTheme"));
                    continue;
                }

                bound.Add(file.FullPath);
                units.Add(new GenerationUnit(
                    target.Kind,
                    target.ClassName,
                    target.Namespace,
                    target.ContainingTypes,
                    null,
                    file.FullPath,
                    file.DisplayPath,
                    PathUtilities.Relative(file.FullPath, globals.ProjectDirectory),
                    file.Text!,
                    target.Kernels ?? file.Kernels ?? globals.Kernels,
                    Merge(target.Settings, file.Settings),
                    HintName(target.Namespace, target.ContainingTypes, target.ClassName),
                    target.IsPublic));
            }

            foreach (var file in files)
            {
                if (file.Kind is not { } kind || bound.Contains(file.FullPath))
                {
                    continue;
                }

                if (file.Text is null)
                {
                    diagnostics.Add(DiagnosticInfo.Create(
                        TintDiagnostics.InvalidFile, LocationInfo.InFile(file.DisplayPath), PathUtilities.Relative(file.FullPath, globals.ProjectDirectory), kind == SourceKind.Grammar ? "grammar" : "theme", "the file cannot be read"));
                    continue;
                }

                var className = file.Name
                    ?? (kind == SourceKind.Grammar
                        ? Naming.GrammarClassName(file.ScopeName ?? PathUtilities.FileNameWithoutExtensions(file.FullPath))
                        : Naming.ThemeClassName(PathUtilities.FileNameWithoutExtensions(file.FullPath)));
                var ns = file.Namespace ?? globals.RootNamespace;
                var accessibility = "internal";
                if (file.Accessibility is { } requested)
                {
                    if (requested is "public" or "internal")
                    {
                        accessibility = requested;
                    }
                    else
                    {
                        diagnostics.Add(DiagnosticInfo.Create(TintDiagnostics.InvalidMetadata, LocationInfo.InFile(file.DisplayPath), requested, "Accessibility", className, "expected 'public' or 'internal'"));
                    }
                }

                units.Add(new GenerationUnit(
                    kind,
                    className,
                    ns,
                    default,
                    accessibility,
                    file.FullPath,
                    file.DisplayPath,
                    PathUtilities.Relative(file.FullPath, globals.ProjectDirectory),
                    file.Text,
                    file.Kernels ?? globals.Kernels,
                    file.Settings,
                    HintName(ns, default, className),
                    accessibility == "public"));
            }

            // Two units with one fully qualified name would not compile; report and keep the first.
            var byName = new Dictionary<string, GenerationUnit>(StringComparer.Ordinal);
            var unique = new List<GenerationUnit>();
            foreach (var unit in units)
            {
                if (byName.TryGetValue(unit.HintName, out var first))
                {
                    diagnostics.Add(DiagnosticInfo.Create(
                        TintDiagnostics.DuplicateClass, LocationInfo.InFile(unit.DisplayPath), unit.HintName, PathUtilities.Relative(first.FullPath, globals.ProjectDirectory), PathUtilities.Relative(unit.FullPath, globals.ProjectDirectory)));
                    continue;
                }

                byName[unit.HintName] = unit;
                unique.Add(unit);
            }

            return new Plan(unique.ToEquatableArray(), diagnostics.ToEquatableArray());
        }

        // A relative attribute path that is not under the project directory binds the one item whose path ends with it,
        // so "csharp/syntaxes/csharp.tmLanguage.json" finds an item included from a package folder; an ambiguous suffix
        // binds nothing (TINT001).
        private static ProjectFile? UniqueSuffixMatch(EquatableArray<ProjectFile> files, string path)
        {
            if (Path.IsPathRooted(path.Replace('\\', '/')))
            {
                return null;
            }

            ProjectFile? match = null;
            foreach (var file in files)
            {
                if (file.Text is not null && EndsWithPath(file.FullPath, path))
                {
                    if (match is not null)
                    {
                        return null;
                    }

                    match = file;
                }
            }

            return match;
        }

        private static bool EndsWithPath(string fullPath, string path)
        {
            path = path.Replace('\\', '/');
            while (path.StartsWith("./", StringComparison.Ordinal))
            {
                path = path.Substring(2);
            }

            return PathUtilities.PathEquals(fullPath, path) || fullPath.EndsWith("/" + path, StringComparison.OrdinalIgnoreCase);
        }

        // Attribute properties win over item metadata.
        private static SourceSettings Merge(SourceSettings attribute, SourceSettings item) => new(
            attribute.LanguageId ?? item.LanguageId,
            attribute.Aliases.Count > 0 ? attribute.Aliases : item.Aliases,
            attribute.FileExtensions.Count > 0 ? attribute.FileExtensions : item.FileExtensions,
            attribute.EmbeddedLanguages.Count > 0 ? attribute.EmbeddedLanguages : item.EmbeddedLanguages,
            attribute.InjectTo.Count > 0 ? attribute.InjectTo : item.InjectTo,
            attribute.InjectionSelector ?? item.InjectionSelector,
            attribute.TokenTypes.Count > 0 ? attribute.TokenTypes : item.TokenTypes,
            attribute.BalancedBracketScopes ?? item.BalancedBracketScopes,
            attribute.UnbalancedBracketScopes.Count > 0 ? attribute.UnbalancedBracketScopes : item.UnbalancedBracketScopes,
            attribute.ThemeMode ?? item.ThemeMode);

        private static string HintName(string? ns, EquatableArray<string> containingTypes, string className)
        {
            var parts = new List<string>();
            if (ns is not null)
            {
                parts.Add(ns);
            }

            parts.AddRange(containingTypes.Select(t => t.Substring(t.LastIndexOf(' ') + 1)));
            parts.Add(className);
            return string.Join(".", parts);
        }
    }
}
