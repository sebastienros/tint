namespace Tint.Generator;

// The class a TintGrammarsClass or TintThemesClass property names: in the root namespace, or in the namespace the
// value spells out (My.Bundles.Grammars).
internal sealed record AggregateTarget(string? Namespace, string ClassName)
{
    public static AggregateTarget? From(string? value, string? rootNamespace)
    {
        if (value is null)
        {
            return null;
        }

        var dot = value.LastIndexOf('.');
        return dot < 0
            ? new AggregateTarget(rootNamespace, value)
            : new AggregateTarget(value.Substring(0, dot), value.Substring(dot + 1));
    }
}

// Emits a static class listing every generated grammar or theme of the compilation: All, Find and one property per
// class. All and Find live in nested holder classes so that a trimmed application that only reads one property keeps
// only that class.
internal static class AggregateEmitter
{
    private const string GrammarSource = "global::Tint.Grammars.IGrammarSource";
    private const string ThemeSource = "global::Tint.Themes.IThemeSource";

    public static GenerationResult Generate(AggregateTarget target, SourceKind kind, EquatableArray<AggregateEntry> entries)
    {
        var grammar = kind == SourceKind.Grammar;
        var sourceType = grammar ? GrammarSource : ThemeSource;
        var suffix = grammar ? "Grammar" : "Theme";
        var ordered = entries
            .OrderBy(e => grammar ? e.Key ?? string.Empty : e.ClassName, StringComparer.Ordinal)
            .ThenBy(e => e.TypeName, StringComparer.Ordinal)
            .ToList();
        var names = PropertyNames(ordered, suffix, target.ClassName);

        // A public class cannot expose an internal one; internal unless every listed class is public.
        var accessibility = ordered.Count > 0 && ordered.All(e => e.IsPublic) ? "public" : "internal";
        var hintName = target.Namespace is null ? target.ClassName : target.Namespace + "." + target.ClassName;

        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("// Generated by Tint.Generator from the " + (grammar ? "TintGrammarsClass" : "TintThemesClass") + " property.");
        w.Line("#nullable enable");
        w.Line("#pragma warning disable");
        w.Line();
        if (target.Namespace is not null)
        {
            w.Open("namespace " + target.Namespace);
        }

        w.Line("/// <summary>The " + (grammar ? "grammars" : "themes") + " generated in this assembly.</summary>");
        w.Line("[global::System.CodeDom.Compiler.GeneratedCode(\"Tint.Generator\", \"" + typeof(AggregateEmitter).Assembly.GetName().Version + "\")]");
        w.Open(accessibility + " static partial class " + target.ClassName);

        w.Line("/// <summary>Every " + (grammar ? "grammar, ordered by scope name" : "theme, ordered by class name") + ". Reading it keeps every class in a trimmed application.</summary>");
        w.Line("public static global::System.Collections.Generic.IReadOnlyList<" + sourceType + "> All => __TintAll.Items;");
        w.Line();
        if (grammar)
        {
            w.Line("/// <summary>Finds a grammar by its scope name, for example <c>source.cs</c>; null when there is none.</summary>");
            w.Line("/// <param name=\"scopeName\">The root scope name of the grammar.</param>");
            w.Open("public static " + sourceType + "? Find(string scopeName)");
            w.Line("global::System.ArgumentNullException.ThrowIfNull(scopeName);");
            w.Line("return __TintIndex.Items.TryGetValue(scopeName, out var source) ? source : null;");
        }
        else
        {
            w.Line("/// <summary>");
            w.Line("/// Finds a theme by its name (<c>Dark+</c>) or its property name here (<c>DarkPlus</c>), ignoring case; null when");
            w.Line("/// there is none.");
            w.Line("/// </summary>");
            w.Line("/// <param name=\"name\">The name of the theme, or of its property.</param>");
            w.Open("public static " + sourceType + "? Find(string name)");
            w.Line("global::System.ArgumentNullException.ThrowIfNull(name);");
            w.Line("return __TintIndex.Items.TryGetValue(name, out var source) ? source : null;");
        }

        w.Close();
        foreach (var entry in ordered)
        {
            w.Line();
            w.Line("/// <summary>The " + (entry.Key is null ? string.Empty : "<c>" + Xml(entry.Key) + "</c> ") + suffix.ToLowerInvariant() + ".</summary>");
            w.Line("public static " + entry.TypeName + " " + names[entry] + " => " + entry.TypeName + ".Instance;");
        }

        w.Line();
        w.Open("private static class __TintAll");
        w.Line("public static readonly global::System.Collections.ObjectModel.ReadOnlyCollection<" + sourceType + "> Items = new global::System.Collections.ObjectModel.ReadOnlyCollection<" + sourceType + ">(new " + sourceType + "[]");
        w.Line("{");
        w.Indent();
        foreach (var entry in ordered)
        {
            w.Line(entry.TypeName + ".Instance,");
        }

        w.Unindent();
        w.Line("});");
        w.Close();
        w.Line();

        // First one wins when two classes share a key.
        var comparer = grammar ? "global::System.StringComparer.Ordinal" : "global::System.StringComparer.OrdinalIgnoreCase";
        w.Open("private static class __TintIndex");
        w.Line("public static readonly global::System.Collections.Frozen.FrozenDictionary<string, " + sourceType + "> Items = Build();");
        w.Line();
        w.Open("private static global::System.Collections.Frozen.FrozenDictionary<string, " + sourceType + "> Build()");
        w.Line("var map = new global::System.Collections.Generic.Dictionary<string, " + sourceType + ">(" + comparer + ");");
        w.Line("foreach (var source in __TintAll.Items)").Line("{");
        w.Line(grammar ? "    map.TryAdd(source.ScopeName, source);" : "    if (source.Name is { } name)");
        if (!grammar)
        {
            w.Line("    {").Line("        map.TryAdd(name, source);").Line("    }");
        }

        w.Line("}");
        w.Line();
        if (!grammar)
        {
            // Not every theme file has a name; property names are the fallback.
            for (var i = 0; i < ordered.Count; i++)
            {
                w.Line("map.TryAdd(" + CodeWriter.Literal(names[ordered[i]]) + ", __TintAll.Items[" + i.ToString(System.Globalization.CultureInfo.InvariantCulture) + "]);");
            }

            w.Line();
        }

        w.Line("return global::System.Collections.Frozen.FrozenDictionary.ToFrozenDictionary(map, " + comparer + ");");
        w.Close();
        w.Close();

        w.Close();
        if (target.Namespace is not null)
        {
            w.Close();
        }

        return new GenerationResult(hintName, w.ToString(), null, default);
    }

    // CSharpGrammar -> CSharp. A name that is empty, taken, or clashes with All, Find or the class keeps the class name,
    // then a number.
    private static Dictionary<AggregateEntry, string> PropertyNames(List<AggregateEntry> entries, string suffix, string className)
    {
        var used = new HashSet<string>(StringComparer.Ordinal) { "All", "Find", className };
        var names = new Dictionary<AggregateEntry, string>();
        foreach (var entry in entries)
        {
            var name = entry.ClassName.EndsWith(suffix, StringComparison.Ordinal) ? entry.ClassName.Substring(0, entry.ClassName.Length - suffix.Length) : entry.ClassName;
            if (name.Length == 0 || char.IsDigit(name[0]) || used.Contains(name))
            {
                name = entry.ClassName;
            }

            var unique = name;
            for (var i = 2; used.Contains(unique); i++)
            {
                unique = name + i.ToString(System.Globalization.CultureInfo.InvariantCulture);
            }

            used.Add(unique);
            names[entry] = unique;
        }

        return names;
    }

    private static string Xml(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
