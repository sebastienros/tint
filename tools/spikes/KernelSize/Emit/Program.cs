// Kernel-size spike, step 1: collects every regex of one or more TextMate grammars, applies the
// pre-processing of docs/design.md section 5 (\xHH, \z, \A/\G anchor variants) and writes a C#
// file with one pattern method per distinct pattern text.
//
// Usage: Emit [--lazy] --class <Name> --namespace <Ns> --out <file.cs> <grammar.json>...
//   default : [GeneratedPattern(..., OnigurumaOptions.CaptureGroup)] partial methods (kernels)
//   --lazy  : plain methods that call OnigurumaPattern.Parse on first use (interpreter)
// A manifest (<file>.tsv: index, length, flags, source) is written next to the C# file.

using System.Globalization;
using System.Text;
using System.Text.Json;

var lazy = false;
string? className = null, ns = null, outPath = null;
var grammars = new List<string>();
for (var i = 0; i < args.Length; i++)
{
    switch (args[i])
    {
        case "--lazy":
            lazy = true;
            break;
        case "--class":
            className = args[++i];
            break;
        case "--namespace":
            ns = args[++i];
            break;
        case "--out":
            outPath = args[++i];
            break;
        default:
            grammars.Add(args[i]);
            break;
    }
}

if (className is null || ns is null || outPath is null || grammars.Count == 0)
{
    Console.Error.WriteLine("Usage: Emit [--lazy] --class <Name> --namespace <Ns> --out <file.cs> <grammar.json>...");
    return 2;
}

var stats = new Stats();
// Distinct pre-processed pattern text → the anchor kinds it holds (computed once per text).
var distinct = new Dictionary<string, (bool A, bool G)>(StringComparer.Ordinal);
var distinctOrder = new List<string>();

foreach (var path in grammars)
{
    using var doc = JsonDocument.Parse(File.ReadAllBytes(path), new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip, AllowTrailingCommas = true });
    var before = stats.Patterns;
    WalkRule(doc.RootElement);
    Console.WriteLine($"{Path.GetFileName(path)}: {stats.Patterns - before} patterns");
}

// Expand the anchor variants vscode-textmate builds (A0_G0, A0_G1, A1_G0, A1_G1) and de-duplicate
// again: a pattern with one anchor kind yields two distinct texts, one with both kinds four.
var emitted = new List<(string Text, string Flags)>();
var emittedSet = new HashSet<string>(StringComparer.Ordinal);
foreach (var text in distinctOrder)
{
    var (hasA, hasG) = distinct[text];
    if (hasA)
    {
        stats.WithA++;
    }

    if (hasG)
    {
        stats.WithG++;
    }

    if (hasA && hasG)
    {
        stats.WithBoth++;
    }

    foreach (var allowA in new[] { true, false })
    {
        foreach (var allowG in new[] { true, false })
        {
            var variant = (hasA || hasG) ? AnchorVariant(text, allowA, allowG) : text;
            if (emittedSet.Add(variant))
            {
                var flags = (hasA || hasG) ? $"{(hasA ? (allowA ? "A1" : "A0") : "")}{(hasG ? (allowG ? "G1" : "G0") : "")}" : "-";
                emitted.Add((variant, flags));
            }
        }
    }
}

stats.Distinct = distinctOrder.Count;
stats.Emitted = emitted.Count;

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated> by tools/spikes/KernelSize/Emit from " + string.Join(", ", grammars.Select(Path.GetFileName)) + " </auto-generated>");
sb.AppendLine("#nullable enable");
sb.AppendLine("using GregsEx;");
if (!lazy)
{
    sb.AppendLine("using GregsEx.SourceGeneration;");
}

sb.AppendLine();
sb.AppendLine($"namespace {ns};");
sb.AppendLine();
sb.AppendLine($"public static partial class {className}");
sb.AppendLine("{");
if (lazy)
{
    sb.AppendLine("    // Same raised limits as the TextMateSharp + GregsEx branch.");
    sb.AppendLine("    private static readonly OnigurumaCompileOptions s_options = new(");
    sb.AppendLine("        new RegexCompileLimits(maxPatternUnits: 1 << 22, maxNestingDepth: 4096, maxInstructions: 1 << 24,");
    sb.AppendLine("            maxClassRanges: 1 << 20, maxCaptureGroups: 32767, maxCompileWork: 1L << 32, maxPlanBytes: 1L << 30,");
    sb.AppendLine("            maxCompileMemoryBytes: 1L << 30));");
    sb.AppendLine();
}

sb.AppendLine($"    public const int Count = {emitted.Count};");
sb.AppendLine();
for (var i = 0; i < emitted.Count; i++)
{
    var literal = Literal(emitted[i].Text);
    if (lazy)
    {
        sb.AppendLine($"    private static OnigurumaPattern? s_p{i};");
        sb.AppendLine($"    private static OnigurumaPattern P{i}() => s_p{i} ??= OnigurumaPattern.Parse({literal}, RegexProfiles.OnigurumaTextMate, s_options);");
    }
    else
    {
        sb.AppendLine($"    [GeneratedPattern({literal}, OnigurumaOptions.CaptureGroup)]");
        sb.AppendLine($"    private static partial OnigurumaPattern P{i}();");
    }

    sb.AppendLine();
}

sb.AppendLine("    public static OnigurumaPattern[] All() =>");
sb.AppendLine("    [");
for (var i = 0; i < emitted.Count; i++)
{
    sb.AppendLine($"        P{i}(),");
}

sb.AppendLine("    ];");
sb.AppendLine("}");

Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outPath))!);
File.WriteAllText(outPath, sb.ToString(), new UTF8Encoding(false));

var manifest = new StringBuilder("index\tlength\tvariant\tsource\n");
for (var i = 0; i < emitted.Count; i++)
{
    manifest.Append(i).Append('\t').Append(emitted[i].Text.Length).Append('\t').Append(emitted[i].Flags).Append('\t')
        .Append(Literal(emitted[i].Text)).Append('\n');
}

File.WriteAllText(Path.ChangeExtension(outPath, ".tsv"), manifest.ToString(), new UTF8Encoding(false));

Console.WriteLine($"patterns (match/begin/end/while occurrences): {stats.Patterns} (match {stats.Match}, begin {stats.Begin}, end {stats.End}, while {stats.While})");
Console.WriteLine($"skipped dynamic end/while with back-references: {stats.Dynamic}");
Console.WriteLine($"distinct after pre-processing: {stats.Distinct} (\\xHH rewrites in {stats.HexRewrites}, \\z rewrites in {stats.ZRewrites})");
Console.WriteLine($"distinct with \\A: {stats.WithA}, with \\G: {stats.WithG}, with both: {stats.WithBoth}");
Console.WriteLine($"emitted methods (distinct texts incl. anchor variants): {stats.Emitted}");
Console.WriteLine($"pattern text chars emitted: {emitted.Sum(e => (long)e.Text.Length)}; longest: {emitted.Max(e => e.Text.Length)}");
Console.WriteLine($"wrote {outPath}");
return 0;

void WalkRule(JsonElement rule)
{
    if (rule.ValueKind != JsonValueKind.Object)
    {
        return;
    }

    foreach (var property in rule.EnumerateObject())
    {
        switch (property.Name)
        {
            case "match":
            case "begin":
            case "end":
            case "while":
                if (property.Value.ValueKind == JsonValueKind.String)
                {
                    Collect(property.Name, property.Value.GetString()!);
                }

                break;
            case "patterns":
                if (property.Value.ValueKind == JsonValueKind.Array)
                {
                    foreach (var child in property.Value.EnumerateArray())
                    {
                        WalkRule(child);
                    }
                }

                break;
            case "repository":
            case "injections":
            case "captures":
            case "beginCaptures":
            case "endCaptures":
            case "whileCaptures":
                if (property.Value.ValueKind == JsonValueKind.Object)
                {
                    foreach (var child in property.Value.EnumerateObject())
                    {
                        WalkRule(child.Value);
                    }
                }

                break;
        }
    }
}

void Collect(string key, string source)
{
    stats.Patterns++;
    switch (key)
    {
        case "match":
            stats.Match++;
            break;
        case "begin":
            stats.Begin++;
            break;
        case "end":
            stats.End++;
            break;
        default:
            stats.While++;
            break;
    }

    // vscode-textmate: HAS_BACK_REFERENCES = /\\(\d+)/; such end/while patterns are resolved per match.
    if (key is "end" or "while" && HasBackReference(source))
    {
        stats.Dynamic++;
        return;
    }

    var text = RewriteHex(source, ref stats.HexRewrites);
    text = RewriteZ(text, out var hasA, out var hasG, ref stats.ZRewrites);
    if (!distinct.ContainsKey(text))
    {
        distinct.Add(text, (hasA, hasG));
        distinctOrder.Add(text);
    }
}

static bool HasBackReference(string source)
{
    for (var i = 0; i + 1 < source.Length; i++)
    {
        if (source[i] == '\\' && char.IsAsciiDigit(source[i + 1]))
        {
            return true;
        }
    }

    return false;
}

// Onigwrap's UnicodeCharEscape: \x followed by 2..8 hex digits becomes \x{...}; \x{7fffffff} is clamped.
static string RewriteHex(string pattern, ref int rewrites)
{
    if (!pattern.Contains("\\x", StringComparison.Ordinal))
    {
        return pattern;
    }

    var builder = new StringBuilder(pattern.Length + 8);
    var changed = false;
    var i = 0;
    while (i < pattern.Length)
    {
        if (pattern[i] == '\\' && i + 1 < pattern.Length && pattern[i + 1] == 'x')
        {
            var digits = 0;
            while (digits < 8 && i + 2 + digits < pattern.Length && char.IsAsciiHexDigit(pattern[i + 2 + digits]))
            {
                digits++;
            }

            if (digits >= 2)
            {
                builder.Append("\\x{").Append(pattern, i + 2, digits).Append('}');
                i += 2 + digits;
                changed = true;
                continue;
            }
        }

        builder.Append(pattern[i]);
        i++;
    }

    var result = builder.ToString().Replace("\\x{7fffffff}", "\\x{7ffff}", StringComparison.Ordinal);
    if (changed || !string.Equals(result, pattern, StringComparison.Ordinal))
    {
        rewrites++;
    }

    return result;
}

// vscode-textmate RegExpSource constructor: walks escapes pairwise, rewrites \z to $(?!\n)(?<!\n)
// and notes \A / \G.
static string RewriteZ(string pattern, out bool hasA, out bool hasG, ref int rewrites)
{
    hasA = false;
    hasG = false;
    StringBuilder? builder = null;
    var last = 0;
    for (var pos = 0; pos < pattern.Length; pos++)
    {
        if (pattern[pos] == '\\' && pos + 1 < pattern.Length)
        {
            var next = pattern[pos + 1];
            if (next == 'z')
            {
                builder ??= new StringBuilder(pattern.Length + 16);
                builder.Append(pattern, last, pos - last).Append("$(?!\\n)(?<!\\n)");
                last = pos + 2;
            }
            else if (next == 'A')
            {
                hasA = true;
            }
            else if (next == 'G')
            {
                hasG = true;
            }

            pos++;
        }
    }

    if (builder is null)
    {
        return pattern;
    }

    rewrites++;
    builder.Append(pattern, last, pattern.Length - last);
    return builder.ToString();
}

// vscode-textmate RegExpSource._buildAnchorCache: the letter after a disallowed \A or \G becomes U+FFFF.
static string AnchorVariant(string pattern, bool allowA, bool allowG)
{
    var chars = pattern.ToCharArray();
    for (var pos = 0; pos + 1 < chars.Length; pos++)
    {
        if (chars[pos] == '\\')
        {
            if ((chars[pos + 1] == 'A' && !allowA) || (chars[pos + 1] == 'G' && !allowG))
            {
                chars[pos + 1] = '￿';
            }

            pos++;
        }
    }

    return new string(chars);
}

// Verbatim literal when the text is printable ASCII, a regular escaped literal otherwise.
static string Literal(string text)
{
    if (text.All(c => c is >= ' ' and <= '~'))
    {
        return "@\"" + text.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";
    }

    var builder = new StringBuilder(text.Length + 16).Append('"');
    foreach (var c in text)
    {
        switch (c)
        {
            case '\\':
                builder.Append("\\\\");
                break;
            case '"':
                builder.Append("\\\"");
                break;
            default:
                if (c is >= ' ' and <= '~')
                {
                    builder.Append(c);
                }
                else
                {
                    builder.Append("\\u").Append(((int)c).ToString("X4", CultureInfo.InvariantCulture));
                }

                break;
        }
    }

    return builder.Append('"').ToString();
}

internal sealed class Stats
{
    public int Patterns, Match, Begin, End, While, Dynamic, Distinct, Emitted, WithA, WithG, WithBoth, HexRewrites, ZRewrites;
}
